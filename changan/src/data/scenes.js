//                插到正文里 {{inserts}} 标记所在的位置；多条可同时生效，按数组顺序拼接。
//                用途：让同一段剧情"按你来时的路"多出（或少一段）文字 ——
//                这是把 flag 变成叙事后果的最低成本方式，不需要新增任何节点。
//                因为它不复制原文，所以后续修改默认正文时不会失去同步。
//
//                ⚠️ 为什么用标记定位，而不是"塞最前 / 塞最后"：
//                节点正文往往以转场句开头（例如「你出了靖安司，没有直接去查案。」）。
//                插段若一律塞在第一个字之前，就会读成"先提到葛老、再说你走进葛老的暗市"
//                —— 预告式倒叙。标记让插入点由**正文结构**决定，而不是由作者猜。
//
//                ⚠️ 插段自己也要写成"承接"，不能写成"预告"：
//                它落在标记之后，读起来必须是接着上一句往下走的。
//                反例：「你还没去坊里，葛老却像早算到你会路过这儿。」
//                      （标记在"你绕进了暗市"之后 → 自相矛盾）
//                正例：「你没提闻染，但葛老像是早算到你会来问这个。」
//                漏写标记时会退化为追加到全文末尾，tools/verify.mjs 会给出警告。
//
//   textVariants 条件正文（整段重写）：[{ when, text }]，取第一个 when 成立者。
//                只用于"整场戏基调都变了"的场合 —— 它要复制全文，容易与默认正文失同步。
//                ⚠️ 顺序敏感：越具体的条件越靠前，兜底那条（通常不带 when）放最后。
//
// 选项字段：
//   t            选项文案
//   to           跳转目标
//                  · 字符串 → 固定节点
//                  · 数组   → 条件路由：按顺序取第一个 when 成立的 { when, then }；
//                             最后一项可省略 when，作为兜底
//   flag         置标记（写入 state.flags，可被 require 与路由 when 读取）
//   clue         获得线索
//   trust        信任变化 { 角色id: 增量 }
//   require      出现条件；不满足则该选项不显示。⚠️ 每个节点至少要留一个无条件选项，
//                否则玩家会卡死（tools/verify.mjs 会强制校验）
//   requireHint  条件不满足时显示的提示文案，让玩家知道"还有一条路没走到"
//   tag          自定义角标（'risk' 会显示为「风险」）
//
// 条件表达式支持的键（tools/verify.mjs 会校验键名与引用）：
//   flagsAll:  ['a','b']    需要同时拥有这些 flag
//   flagsAny:  ['a','b']    至少拥有其中之一
//   flagsNone: ['a']        不能拥有这些 flag
