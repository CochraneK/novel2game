// ===== 剧情图遍历的公共入口 =====
//
// ⚠️ 这两个函数是「剧情图」的唯一权威定义。所有工具（verify / simulate /
//    branch_audit / trace_choices）都必须走它们，不要各自再抄一遍 ——
//    抄一遍就会出现"某个工具不知道过场场景存在"的静默漏检。
//
//    加 `next` 这类新字段时，只要在这里补一处，全部工具自动跟上。

// 过场场景：非结局、没有 choices、只有一个 next 出口。
// 它不是一个"抉择点"，玩家只按一次「继续」。
export function isPassage(sc) {
  if (!sc || sc.ending) return false;
  if (Array.isArray(sc.choices) && sc.choices.length) return false;
  return typeof sc.next === 'string' && sc.next.length > 0;
}

// 一个节点所有可能的下一站（条件路由的全部分支都算上，过场场景算它的 next）。
export function nextTargets(sc) {
  if (!sc || sc.ending) return [];
  if (isPassage(sc)) return [sc.next];
  const out = [];
  for (const ch of (sc.choices || [])) {
    const to = ch && ch.to;
    if (typeof to === 'string') out.push(to);
    else if (Array.isArray(to)) for (const r of to) { if (r && r.then) out.push(r.then); }
  }
  return out;
}
