//           tools/branch_audit.mjs 会统计死标记比例。加 flag 时请想清楚它在哪里被消费。
//
// 结局节点：ending: true, endTag, endingText
//
//   next / nextLabel  过场场景（passage）：**没有 choices，只有一个出口**。
